import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel: 'chrome', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
await page.getByRole('heading', { name: /Tell us what you need/ }).scrollIntoViewIfNeeded()
await page.waitForTimeout(900)
await page.screenshot({ path: '/tmp/opencode/advisory-finder.png' })
await page.goto('http://localhost:4173/about', { waitUntil: 'networkidle' })
await page.mouse.wheel(0, 1050)
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/opencode/advisory-mission.png' })
await page.goto('http://localhost:4173/careers', { waitUntil: 'networkidle' })
await page.mouse.wheel(0, 520)
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/opencode/advisory-careers.png' })
await page.goto('http://localhost:4173/contact', { waitUntil: 'networkidle' })
await page.mouse.wheel(0, 1500)
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/opencode/advisory-booking.png' })
await page.goto('http://localhost:4173/services/strategy/corporate-strategy', { waitUntil: 'networkidle' })
await page.mouse.wheel(0, 900)
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/opencode/advisory-service-media.png' })
await browser.close()
console.log('ok')
